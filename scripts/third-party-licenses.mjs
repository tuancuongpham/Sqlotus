// Writes licenses/THIRD_PARTY_LICENSES.md: the license texts of every Rust crate and
// npm package that ships in the app. Run before a release (the installer
// bundles the file); needs cargo-about (`cargo install cargo-about --locked --features cli`).
//
//   node scripts/third-party-licenses.mjs
import { execSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const run = (cmd, args) => execSync([cmd, ...args].join(" "), { encoding: "utf8", maxBuffer: 256 << 20 });
const fence = (text) => "```text\n" + text.replace(/\r\n/g, "\n").trim() + "\n```";
const out = [
  "# Third-party licenses",
  "",
  "Sqlotus includes the open-source software listed below. Generated by `scripts/third-party-licenses.mjs`;",
  "do not edit by hand.",
  "",
  "Sqlotus uses these components unmodified. Their source code is available from their own repositories and from",
  "https://crates.io and https://www.npmjs.com under the name and version listed, at no charge. This includes the",
  "components under the Mozilla Public License 2.0 (MPL-2.0), whose Source Code Form you can obtain there.",
  "",
];

// Rust: cargo-about groups crates under each distinct license text
const about = JSON.parse(run("cargo", ["about", "generate", "--format", "json", "-c", "licenses/about.toml", "--manifest-path", "src-tauri/Cargo.toml"]));
const own = new Set(["sqlotus", "sqlotus-core", "sqlotus-db", "sqlotus-store"]);
const groups = about.licenses
  .map((l) => ({
    ...l,
    crates: [...new Set(l.used_by.map((u) => u.crate).filter((c) => !own.has(c.name)).map((c) => `${c.name} ${c.version}`))].sort(),
  }))
  .filter((l) => l.crates.length > 0)
  .sort((a, b) => a.id.localeCompare(b.id) || b.crates.length - a.crates.length);
const crateCount = new Set(groups.flatMap((g) => g.crates)).size;
out.push(`## Rust crates (${crateCount})`, "");
for (const g of groups) {
  out.push(`### ${g.name} (${g.id})`, "", `Used by: ${g.crates.join(", ")}`, "", fence(g.text), "");
}

// npm: production dependencies bundled into the UI
const paths = run("npm", ["ls", "--omit=dev", "--all", "--parseable"]).split(/\r?\n/).filter(Boolean).slice(1);
const seen = new Set();
const packages = [];
for (const dir of paths) {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const key = `${pkg.name} ${pkg.version}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice|thirdpartynotices)/i.test(f));
  if (files.length === 0) throw new Error(`no license file in ${dir}`);
  packages.push({ key, license: pkg.license ?? "see text", texts: files.map((f) => readFileSync(join(dir, f), "utf8")) });
}
packages.sort((a, b) => a.key.localeCompare(b.key));
out.push(`## npm packages (${packages.length})`, "");
for (const p of packages) {
  out.push(`### ${p.key} (${p.license})`, "", ...p.texts.map(fence).flatMap((t) => [t, ""]));
}

const target = "licenses/THIRD_PARTY_LICENSES.md";
writeFileSync(target, out.join("\n"));
console.log(`${target}: ${crateCount} crates, ${packages.length} npm packages`);
