fn set(lists: &[&[&'static str]]) -> HashSet<&'static str> {
    lists.iter().flat_map(|l| l.iter().copied()).collect()
}

static MSSQL: LazyLock<HashSet<&'static str>> =
    LazyLock::new(|| set(&[COMMON_RESERVED, MSSQL_RESERVED]));
static POSTGRES: LazyLock<HashSet<&'static str>> =
    LazyLock::new(|| set(&[COMMON_RESERVED, POSTGRES_RESERVED]));
static MYSQL: LazyLock<HashSet<&'static str>> =
    LazyLock::new(|| set(&[COMMON_RESERVED, MYSQL_RESERVED]));
static FUNCTION_SET: LazyLock<HashSet<&'static str>> = LazyLock::new(|| set(&[FUNCTIONS]));
static TYPE_SET: LazyLock<HashSet<&'static str>> = LazyLock::new(|| set(&[DATA_TYPES]));

/// `upper` must already be ASCII-uppercased.
pub fn is_reserved(upper: &str, dialect: Dialect) -> bool {
    match dialect {
        Dialect::MsSql => MSSQL.contains(upper),
        Dialect::Postgres => POSTGRES.contains(upper),
        Dialect::MySql => MYSQL.contains(upper),
    }
}

pub fn is_function(upper: &str) -> bool {
    FUNCTION_SET.contains(upper)
}

pub fn is_data_type(upper: &str) -> bool {
    TYPE_SET.contains(upper)
}

/// Keywords offered by completion, sorted, for the given dialect.
pub fn completion_keywords(dialect: Dialect) -> Vec<&'static str> {
    let set = match dialect {
        Dialect::MsSql => &*MSSQL,
        Dialect::Postgres => &*POSTGRES,
        Dialect::MySql => &*MYSQL,
    };
    let mut v: Vec<_> = set.iter().copied().collect();
    v.sort_unstable();
    v
}

pub fn functions() -> &'static [&'static str] {
    FUNCTIONS
}

pub fn data_types() -> &'static [&'static str] {
    DATA_TYPES
}
