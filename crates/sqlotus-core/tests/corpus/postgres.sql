-- @case plpgsql function
create or replace function public.order_total(p_customer integer, p_since date default current_date - 30) returns numeric language plpgsql stable as $$
declare
    v_total numeric := 0;
    r record;
begin
    for r in select total from orders where customer_id = p_customer and created_at >= p_since loop
        v_total := v_total + r.total;
    end loop;
    if v_total > 1000 then
        raise notice 'big customer %: %', p_customer, v_total;
    elsif v_total = 0 then
        raise exception 'no orders for %', p_customer using errcode = 'P0002';
    end if;
    return v_total;
exception
    when others then
        raise warning 'failed: %', sqlerrm;
        return null;
end;
$$;
