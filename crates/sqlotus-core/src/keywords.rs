static QUOTE_MSSQL: LazyLock<HashSet<&'static str>> = LazyLock::new(|| set(&[TSQL_OFFICIAL]));
static QUOTE_POSTGRES: LazyLock<HashSet<&'static str>> = LazyLock::new(|| set(&[POSTGRES_OFFICIAL]));
static QUOTE_MYSQL: LazyLock<HashSet<&'static str>> = LazyLock::new(|| set(&[MYSQL_OFFICIAL]));

/// Whether an identifier spelled `upper` must be quoted: one of the
/// server's reserved words (the keyword lists above are for editing and
/// formatting and are not complete for that).
pub fn must_quote(upper: &str, dialect: Dialect) -> bool {
    is_reserved(upper, dialect)
        || match dialect {
            Dialect::MsSql => QUOTE_MSSQL.contains(upper),
            Dialect::Postgres => QUOTE_POSTGRES.contains(upper),
            Dialect::MySql => QUOTE_MYSQL.contains(upper),
        }
}

/// `upper` must already be ASCII-uppercased.
pub fn is_reserved(upper: &str, dialect: Dialect) -> bool {
    match dialect {
        Dialect::MsSql => MSSQL.contains(upper),
        Dialect::Postgres => POSTGRES.contains(upper),
        Dialect::MySql => MYSQL.contains(upper),
    }
}

pub fn is_function(upper: &str) -> bool {
    FUNCTION_SET.contains(upper)
}

pub fn is_data_type(upper: &str) -> bool {
    TYPE_SET.contains(upper)
}

/// Keywords offered by completion, sorted, for the given dialect.
pub fn completion_keywords(dialect: Dialect) -> Vec<&'static str> {
    let set = match dialect {
        Dialect::MsSql => &*MSSQL,
        Dialect::Postgres => &*POSTGRES,
        Dialect::MySql => &*MYSQL,
    };
    let mut v: Vec<_> = set.iter().copied().collect();
    v.sort_unstable();
    v
}

pub fn functions() -> &'static [&'static str] {
    FUNCTIONS
}

pub fn data_types() -> &'static [&'static str] {
    DATA_TYPES
}
